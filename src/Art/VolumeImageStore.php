<?php

declare(strict_types=1);

namespace Felkyo\Art;

/**
 * The picture store as a folder on a disk — the Railway volume in production,
 * storage/art/ on a development machine.
 *
 * @package Felkyo\Art
 *
 * THE ONE RULE THAT MAKES THIS SAFE: the folder is OUTSIDE the web root
 * (public/). Nothing in it is ever reachable by URL directly, and nothing in
 * it can ever be executed by the web server, whatever its bytes are. The only
 * way a picture reaches a browser is ArtController reading it through get()
 * and sending it with the content type the site itself recorded.
 *
 * NAMES ARE NEVER PATHS. Every name that arrives here is a content hash plus
 * extension, generated by the site. Even so, the guard below refuses anything
 * that is not exactly that shape — belt and braces on the one class that
 * touches the filesystem, so a bug elsewhere cannot become a path traversal.
 */
final class VolumeImageStore implements ImageStore
{
    // Exactly what a stored name looks like: 64 hex characters, a dot, and
    // one of the three extensions the validator can produce.
    private const NAME_SHAPE = '/^[a-f0-9]{64}\.(gif|png|webp)$/';

    public function __construct(private string $folder)
    {
    }

    public function put(string $storedName, string $bytes): void
    {
        $this->ensureFolderExists();

        // Write to a temporary name, then rename: a rename is atomic on the
        // same disk, so a request that reads while we write sees either the
        // whole old file or the whole new one — never half a picture.
        $temporary = $this->pathFor($storedName) . '.part';
        if (file_put_contents($temporary, $bytes) === false) {
            throw new \RuntimeException('Could not write the picture to the art folder.');
        }
        rename($temporary, $this->pathFor($storedName));
    }

    public function get(string $storedName): ?string
    {
        $path = $this->pathFor($storedName);
        if (!is_file($path)) {
            return null;
        }

        $bytes = file_get_contents($path);

        return $bytes === false ? null : $bytes;
    }

    public function delete(string $storedName): void
    {
        $path = $this->pathFor($storedName);
        if (is_file($path)) {
            unlink($path);
        }
    }

    public function has(string $storedName): bool
    {
        return is_file($this->pathFor($storedName));
    }

    /**
     * The full path for a name — after refusing any name that is not the
     * exact hash-plus-extension shape. Throws rather than returns, because a
     * wrong-shaped name here means a bug upstream, not a user mistake.
     */
    private function pathFor(string $storedName): string
    {
        if (!preg_match(self::NAME_SHAPE, $storedName)) {
            throw new \InvalidArgumentException('Refusing a stored name that is not a content hash: ' . $storedName);
        }

        return rtrim($this->folder, '/\\') . DIRECTORY_SEPARATOR . $storedName;
    }

    /**
     * Make the folder if it is missing — a fresh checkout, or a volume mounted
     * empty for the first time. Quietly, and only once per request.
     */
    private function ensureFolderExists(): void
    {
        if (!is_dir($this->folder)) {
            mkdir($this->folder, 0755, true);
        }
    }
}
